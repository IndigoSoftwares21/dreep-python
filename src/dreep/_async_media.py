"""Media methods of the asynchronous client: listing, deletion and processing.

Source of truth for ``_sync_media.py`` (generated by ``scripts/unasync.py``).
"""

from __future__ import annotations

from collections.abc import AsyncIterator
from datetime import timedelta
from typing import Any

from . import _constants as c
from ._async_uploads import AsyncUploadsMixin
from ._config import NOT_GIVEN, TimeoutArg
from ._files import FileInput, open_file
from ._http import Operation, parse_text_response, text_request
from ._models import BackgroundRemovedAsset, ConvertedDocument, MediaItem, MediaPage
from ._models_project import OCRResult
from ._operations_media import (
    op_convert_document,
    op_delete_media,
    op_extract_text,
    op_list_media,
    op_remove_background,
)
from ._transform_constants import TEXT_TRANSFORM
from .types import BackgroundRemovalFormat, ConvertFormat


class AsyncMediaMixin(AsyncUploadsMixin):
    async def list_media(
        self,
        *,
        page: int | None = None,
        limit: int | None = None,
        folder: str | None = None,
        folder_id: str | None = None,
        recursive: bool | None = None,
        timeout: TimeoutArg = NOT_GIVEN,
    ) -> MediaPage:
        """Lists one page of ready assets, with the total across all pages.

        Unconfirmed presigned uploads are not listed. To walk every page, use
        :meth:`list_all_media`.
        """
        op = op_list_media(
            page=page, limit=limit, folder=folder, folder_id=folder_id, recursive=recursive
        )
        return await self._run(op, timeout)

    async def list_all_media(
        self,
        *,
        limit: int = c.DEFAULT_PAGE_SIZE,
        folder: str | None = None,
        folder_id: str | None = None,
        recursive: bool | None = None,
        timeout: TimeoutArg = NOT_GIVEN,
    ) -> AsyncIterator[MediaItem]:
        """Yields every asset across every page, fetching pages lazily.

        The next page is requested only when the item after the last one is
        asked for, so breaking out of the loop stops the requests too.
        """
        page = 1
        seen = 0
        while True:
            listing = await self.list_media(
                page=page,
                limit=limit,
                folder=folder,
                folder_id=folder_id,
                recursive=recursive,
                timeout=timeout,
            )
            for item in listing.assets:
                yield item
            seen += len(listing.assets)
            # Stop on a short page *and* on the reported total: either alone
            # would loop forever if the other were missing or wrong.
            if len(listing.assets) < limit or seen >= listing.pagination.total:
                return
            page += 1

    async def delete_media(self, media_id: str, *, timeout: TimeoutArg = NOT_GIVEN) -> None:
        """Deletes an asset and every cached transform derived from it.

        Immediate and permanent: URLs already handed out, signed ones included,
        stop resolving. Not retried; a 404 on your own retry usually means the
        first attempt succeeded.
        """
        await self._run(op_delete_media(media_id), timeout)

    async def remove_background(
        self,
        file: FileInput,
        *,
        filename: str | None = None,
        format: BackgroundRemovalFormat | None = None,
        folder: str | None = None,
        folder_id: str | None = None,
        auto_create_folders: bool | None = None,
        timeout: TimeoutArg = NOT_GIVEN,
    ) -> BackgroundRemovedAsset:
        """Cuts the subject out of an image and stores it, alpha channel kept.

        One removal serves any background colour: pass ``bg`` to :meth:`url`.
        """
        with open_file(file, filename=filename) as prepared:
            op = op_remove_background(
                prepared,
                format=format,
                folder=folder,
                folder_id=folder_id,
                auto_create_folders=auto_create_folders,
            )
            return await self._run(op, timeout)

    async def extract_text(
        self,
        file: FileInput,
        *,
        filename: str | None = None,
        folder: str | None = None,
        folder_id: str | None = None,
        auto_create_folders: bool | None = None,
        include_blocks: bool | None = None,
        timeout: TimeoutArg = NOT_GIVEN,
    ) -> OCRResult:
        """Runs OCR over an uploaded image or PDF.

        With a folder, the text is also stored as a ``.txt`` asset. For an asset
        already in Dreep, use :meth:`fetch_text` instead of re-uploading it.
        """
        with open_file(file, filename=filename) as prepared:
            op = op_extract_text(
                prepared,
                folder=folder,
                folder_id=folder_id,
                auto_create_folders=auto_create_folders,
                include_blocks=include_blocks,
            )
            return await self._run(op, timeout)

    async def fetch_text(
        self,
        asset: Any,
        *,
        expires_in: int | timedelta | None = None,
        timeout: TimeoutArg = NOT_GIVEN,
    ) -> str:
        """OCR text of an asset already in Dreep. Cached after the first read.

        Pass ``expires_in`` for an asset in a signed folder; the request is
        then signed with your signing secret. Raises
        :class:`DreepProcessingError` while the text is still being extracted.
        """
        url = (
            self.url(asset, TEXT_TRANSFORM)
            if expires_in is None
            else self.signed_url(asset, expires_in=expires_in, transform=TEXT_TRANSFORM)
        )
        return await self._run(Operation(text_request(url), str), timeout, parse_text_response)

    async def convert_document(
        self,
        file: FileInput,
        *,
        format: ConvertFormat,
        filename: str | None = None,
        page: int | None = None,
        key: str | None = None,
        folder: str | None = None,
        folder_id: str | None = None,
        auto_create_folders: bool | None = None,
        timeout: TimeoutArg = NOT_GIVEN,
    ) -> ConvertedDocument:
        """Converts a document (Word to PDF, PDF to Word, a PDF page to an image…).

        The API waits up to two minutes. A longer conversion returns with
        ``status == "processing"``; its ``url`` answers 202 until ready.
        """
        with open_file(file, filename=filename) as prepared:
            op = op_convert_document(
                prepared,
                format=format,
                page=page,
                key=key,
                folder=folder,
                folder_id=folder_id,
                auto_create_folders=auto_create_folders,
            )
            return await self._run(op, timeout)
