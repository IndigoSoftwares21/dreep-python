"""Upload methods of the asynchronous client.

Source of truth for ``_sync_uploads.py`` (generated by ``scripts/unasync.py``).
"""

from __future__ import annotations

import anyio

from . import _constants as c
from ._async_core import AsyncCore
from ._config import NOT_GIVEN, TimeoutArg
from ._errors import DreepConflictError
from ._files import FileInput, PreparedFile, aiter_chunks, open_file
from ._http import Operation, Request, discard
from ._models import Asset, PresignedUpload
from ._operations_media import op_confirm_upload, op_presign_upload, op_upload
from ._retry import retry_delay
from .types import Transform


class AsyncUploadsMixin(AsyncCore):
    async def upload(
        self,
        file: FileInput,
        *,
        filename: str | None = None,
        content_type: str | None = None,
        folder: str | None = None,
        key: str | None = None,
        folder_id: str | None = None,
        auto_create_folders: bool | None = None,
        transform: Transform | None = None,
        preset_key: str | None = None,
        timeout: TimeoutArg = NOT_GIVEN,
    ) -> Asset:
        """Uploads a file in one multipart request, optionally transforming it first.

        Good up to a few hundred MB; for larger files use :meth:`upload_presigned`.
        A transform here is applied *before* storage and replaces the original.
        Never retried automatically: a repeat would store a duplicate.

        Args:
            file: ``bytes``, a ``pathlib.Path``, or a binary file object.
            folder: Slug path of the destination; missing folders are created.
            key: Full object key (folder path + filename). Excludes ``folder``.
            folder_id: UUID of an existing folder.
            auto_create_folders: ``False`` to require the folder path to exist.
            preset_key: A saved preset, applied instead of ``transform``.
        """
        with open_file(file, filename=filename, content_type=content_type) as prepared:
            op = op_upload(
                prepared,
                folder=folder,
                key=key,
                folder_id=folder_id,
                auto_create_folders=auto_create_folders,
                transform=transform,
                preset_key=preset_key,
            )
            return await self._run(op, timeout)

    async def presign_upload(
        self,
        *,
        content_type: str,
        size_bytes: int,
        filename: str | None = None,
        folder: str | None = None,
        key: str | None = None,
        folder_id: str | None = None,
        auto_create_folders: bool | None = None,
        format: str | None = None,
        preset_key: str | None = None,
        content_hash: str | None = None,
        timeout: TimeoutArg = NOT_GIVEN,
    ) -> PresignedUpload:
        """Starts a direct-to-storage upload, for large files and browser clients.

        PUT the bytes to ``upload_url`` with exactly this ``content_type`` and
        ``size_bytes``, then call :meth:`confirm_upload`. Pass the file's hex
        SHA-256 as ``content_hash`` to skip content Dreep already stores.
        """
        op = op_presign_upload(
            content_type=content_type,
            size_bytes=size_bytes,
            filename=filename,
            folder=folder,
            key=key,
            folder_id=folder_id,
            auto_create_folders=auto_create_folders,
            format=format,
            preset_key=preset_key,
            content_hash=content_hash,
        )
        return await self._run(op, timeout)

    async def confirm_upload(
        self,
        upload_id: str,
        *,
        transform: Transform | None = None,
        preset_key: str | None = None,
        timeout: TimeoutArg = NOT_GIVEN,
    ) -> Asset:
        """Finalises a presigned upload once its bytes are in storage.

        Raises :class:`DreepConflictError` if the bytes haven't landed yet --
        retry the confirm, not the upload.
        """
        op = op_confirm_upload(upload_id, transform=transform, preset_key=preset_key)
        return await self._run(op, timeout)

    async def upload_presigned(
        self,
        file: FileInput,
        *,
        filename: str | None = None,
        content_type: str | None = None,
        folder: str | None = None,
        key: str | None = None,
        folder_id: str | None = None,
        auto_create_folders: bool | None = None,
        transform: Transform | None = None,
        preset_key: str | None = None,
        content_hash: str | None = None,
        timeout: TimeoutArg = NOT_GIVEN,
    ) -> Asset:
        """Presign, PUT and confirm in one call -- the path for large files.

        The bytes stream straight to storage without being held in memory or
        passing through the API. The PUT is skipped when ``content_hash``
        matches stored content, and the confirm is retried while the bytes
        settle (the API answers 409 until they have).
        """
        with open_file(file, filename=filename, content_type=content_type) as prepared:
            if prepared.size is None:
                raise ValueError("Can't determine the file's size; pass size-aware input.")
            presigned = await self.presign_upload(
                content_type=prepared.content_type,
                size_bytes=prepared.size,
                filename=None if key else prepared.filename,
                folder=folder,
                key=key,
                folder_id=folder_id,
                auto_create_folders=auto_create_folders,
                content_hash=content_hash,
                timeout=timeout,
            )
            if not presigned.already_exists and presigned.upload_url:
                await self._put_bytes(presigned.upload_url, prepared, timeout)
        return await self._confirm_settled(presigned.id, transform, preset_key, timeout)

    async def _put_bytes(self, url: str, prepared: PreparedFile, timeout: TimeoutArg) -> None:
        # Storage checks both headers against what was presigned. The URL is
        # absolute, so no API key is attached; as a PUT it is never retried.
        request = Request(
            c.Method.PUT,
            url,
            headers={
                c.Header.CONTENT_TYPE: prepared.content_type,
                c.Header.CONTENT_LENGTH: str(prepared.size),
            },
            content=aiter_chunks(prepared.stream, c.STREAM_CHUNK_SIZE),
            is_upload=True,
        )
        await self._run(Operation(request, discard), timeout)

    async def _confirm_settled(
        self,
        upload_id: str,
        transform: Transform | None,
        preset_key: str | None,
        timeout: TimeoutArg,
    ) -> Asset:
        for attempt in range(c.CONFIRM_ATTEMPTS):
            try:
                return await self.confirm_upload(
                    upload_id, transform=transform, preset_key=preset_key, timeout=timeout
                )
            except DreepConflictError as error:
                if attempt == c.CONFIRM_ATTEMPTS - 1:
                    raise
                await anyio.sleep(retry_delay(attempt, error))
        raise AssertionError("unreachable")  # pragma: no cover
