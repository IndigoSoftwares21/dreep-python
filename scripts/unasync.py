"""Generates the synchronous client from the asynchronous one.

The async modules are the single source of truth; the sync modules are derived
by token substitution, the approach ``httpcore`` uses. This keeps the two
clients identical in behaviour, signatures and docs without hand-copying.

    python scripts/unasync.py          # regenerate
    python scripts/unasync.py --check  # exit 1 if a generated file is stale (CI)
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Final

PACKAGE: Final = Path(__file__).resolve().parent.parent / "src" / "dreep"

#: async source module -> generated sync module.
FILES: Final = {
    "_async_core.py": "_sync_core.py",
    "_async_uploads.py": "_sync_uploads.py",
    "_async_media.py": "_sync_media.py",
    "_async_project.py": "_sync_project.py",
    "_async_client.py": "_client.py",
}

#: Whole-word substitutions, applied in order. Longer tokens come first.
SUBSTITUTIONS: Final = (
    ("AsyncDreep", "Dreep"),
    ("AsyncCore", "SyncCore"),
    ("AsyncUploadsMixin", "UploadsMixin"),
    ("AsyncMediaMixin", "MediaMixin"),
    ("AsyncProjectMixin", "ProjectMixin"),
    ("AsyncClient", "Client"),
    ("AsyncIterator", "Iterator"),
    ("_async_core", "_sync_core"),
    ("_async_uploads", "_sync_uploads"),
    ("_async_media", "_sync_media"),
    ("_async_project", "_sync_project"),
    ("_async_client", "_client"),
    ("aiter_chunks", "iter_chunks"),
    ("__aenter__", "__enter__"),
    ("__aexit__", "__exit__"),
    ("aclose", "close"),
    ("anyio.sleep", "time.sleep"),
    ("import anyio", "import time"),
    ("asynchronous", "synchronous"),
)
#: Keyword substitutions: these match the keyword plus following space.
KEYWORDS: Final = (
    ("async def ", "def "),
    ("async for ", "for "),
    ("async with ", "with "),
    ("await ", ""),
)

HEADER: Final = (
    "# This file is generated by scripts/unasync.py from {source}.\n"
    "# Do not edit it by hand: change {source} and regenerate.\n"
)


def unasync(source: str, source_name: str) -> str:
    text = source
    for old, new in SUBSTITUTIONS:
        text = re.sub(rf"(?<!\w){re.escape(old)}(?!\w)", new, text)
    for old, new in KEYWORDS:
        text = re.sub(rf"(?<!\w){re.escape(old)}", new, text)
    return _format(HEADER.format(source=source_name) + text)


def _format(text: str) -> str:
    """Sorts imports and formats with ruff, matching what the linters leave.

    Renaming modules reorders imports and dropping ``await`` shortens lines;
    without this step the generated files and the linters would disagree forever.
    """
    ruff = shutil.which("ruff") or str(Path(sys.executable).with_name("ruff"))
    stdin_name = ["--stdin-filename", str(PACKAGE / "generated.py"), "-"]
    for command in (["check", "--select", "I", "--fix", "--quiet", "--exit-zero"], ["format"]):
        text = subprocess.run(
            [ruff, *command, *stdin_name], input=text, capture_output=True, text=True, check=True
        ).stdout
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if output is stale")
    args = parser.parse_args()

    stale = []
    for source_name, target_name in FILES.items():
        expected = unasync((PACKAGE / source_name).read_text(), source_name)
        target = PACKAGE / target_name
        current = target.read_text() if target.exists() else None
        if current == expected:
            continue
        if args.check:
            stale.append(target_name)
        else:
            target.write_text(expected)
            sys.stdout.write(f"generated {target_name}\n")

    if stale:
        sys.stderr.write(f"Stale generated files: {', '.join(stale)}. Run scripts/unasync.py.\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
