"""Project methods of the asynchronous client: folders, presets and usage.

Source of truth for ``_sync_project.py`` (generated by ``scripts/unasync.py``).
"""

from __future__ import annotations

from ._async_core import AsyncCore
from ._config import NOT_GIVEN, TimeoutArg
from ._models_project import Folder, FolderListing, Preset, Usage
from ._operations_project import (
    op_create_folder,
    op_create_preset,
    op_delete_preset,
    op_get_usage,
    op_list_folders,
    op_list_presets,
)
from .types import AccessControlType, Transform


class AsyncProjectMixin(AsyncCore):
    async def create_folder(
        self,
        *,
        name: str | None = None,
        path: str | None = None,
        parent_id: str | None = None,
        parent_path: str | None = None,
        access_control_type: AccessControlType | None = None,
        default_expiry_seconds: int | None = None,
        timeout: TimeoutArg = NOT_GIVEN,
    ) -> Folder:
        """Creates a folder: one by ``name``, or a whole chain by ``path``.

        Uploads create folders on demand, so this is only needed to set the
        access control before anything lands. Subfolders inherit it.
        """
        op = op_create_folder(
            name=name,
            path=path,
            parent_id=parent_id,
            parent_path=parent_path,
            access_control_type=access_control_type,
            default_expiry_seconds=default_expiry_seconds,
        )
        return await self._run(op, timeout)

    async def list_folders(
        self,
        *,
        path: str | None = None,
        parent_id: str | None = None,
        root_only: bool = False,
        timeout: TimeoutArg = NOT_GIVEN,
    ) -> FolderListing:
        """Lists folders with their full paths.

        With no filter, returns every folder at any depth -- enough to build
        the tree in one call. ``path``/``parent_id`` list one folder's
        children; ``root_only`` lists top-level folders.
        """
        op = op_list_folders(path=path, parent_id=parent_id, root_only=root_only)
        return await self._run(op, timeout)

    async def create_preset(
        self,
        *,
        key: str,
        name: str,
        transform: Transform,
        timeout: TimeoutArg = NOT_GIVEN,
    ) -> Preset:
        """Saves a named transform; apply it anywhere with ``{"preset": key}``."""
        return await self._run(op_create_preset(key=key, name=name, transform=transform), timeout)

    async def list_presets(self, *, timeout: TimeoutArg = NOT_GIVEN) -> list[Preset]:
        """Every saved preset on the project."""
        return await self._run(op_list_presets(), timeout)

    async def delete_preset(self, preset_id: str, *, timeout: TimeoutArg = NOT_GIVEN) -> None:
        """Deletes a preset by ``id`` (not ``key``). URLs still using it start failing."""
        await self._run(op_delete_preset(preset_id), timeout)

    async def get_usage(self, *, timeout: TimeoutArg = NOT_GIVEN) -> Usage:
        """Storage consumed and object counts for the project."""
        return await self._run(op_get_usage(), timeout)
